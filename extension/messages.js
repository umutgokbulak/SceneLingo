// The language of the interface: the user's choice, or with 'auto' the browser's own language
// where the interface has been written in it, and English everywhere else.
let slUiLang = 'en';
function slSetUiLang(choice) {
  const browser = typeof navigator !== 'undefined' && navigator.language ? navigator.language.toLowerCase().split('-')[0] : 'en';
  const wanted = choice && choice !== 'auto' ? choice : browser;
  slUiLang = SL_TEXTS[wanted] ? wanted : 'en';
  return slUiLang;
}
slSetUiLang('auto');

function slT(key, ...values) {
  const text = SL_TEXTS[slUiLang][key] !== undefined ? SL_TEXTS[slUiLang][key] : SL_TEXTS.en[key];
  if (text === undefined) return key;
  return text.replace(/\{(\d)\}/g, (m, i) => (values[i] === undefined ? '' : values[i]));
}

// The name of a language in the language of the interface ("German", "Almanca").
function slLangName(code) {
  try {
    const name = new Intl.DisplayNames([slUiLang], { type: 'language' }).of(code);
    return name && name !== code ? name.charAt(0).toLocaleUpperCase(slUiLang) + name.slice(1) : String(code).toUpperCase();
  } catch (e) {
    return String(code).toUpperCase();
  }
}

// Fills in the texts of a page written with data-t="key" (and data-t-title="key" for tooltips).
function slApply(root) {
  for (const node of root.querySelectorAll('[data-t]')) node.textContent = slT(node.dataset.t);
  for (const node of root.querySelectorAll('[data-t-title]')) node.title = slT(node.dataset.tTitle);
  for (const node of root.querySelectorAll('[data-t-placeholder]')) node.placeholder = slT(node.dataset.tPlaceholder);
}

if (typeof module !== 'undefined') module.exports = { SL_TEXTS, slSetUiLang, slT, slLangName };
